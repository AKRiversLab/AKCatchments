  pts <- data.frame(site_code = c("A", "B"), lat = c(ll[2], 10), lon = c(ll[1], 10))
  res <- suppressMessages(suppressWarnings(ak_catchments(pts, dem_source = "local", dem_dir = s$dir, start_buffer_m = 10000,
